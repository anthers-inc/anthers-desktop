// Verify the web-dist release asset's Ed25519 signature.
//
// The format contract's owner is the main repository's `scripts/sign-web-dist.ts`;
// this module is that contract's desktop half. What it accepts is the two-line text
// form — a comment line, then standard base64 — of a signature (64 bytes over the
// archive's exact bytes) and of the public key (32 bytes, raw). `resolve-web.ts`
// verifies every pinned download against the committed `web-dist-signing.pub` and
// fails closed on a missing, malformed or wrong signature: an installed-but-false
// web layer is the one failure that must never happen.
//
// The fixture in `web-sig.test.ts` was generated by the owning script, so the two
// implementations agreeing on one format is a test result, not an assumption.

import { createPublicKey, verify as cryptoVerify, type KeyObject } from "node:crypto";

// The fixed 12-byte SPKI prefix turns a 32-byte raw Ed25519 public key into the DER
// `createPublicKey` accepts. Every Ed25519 SPKI is this exact shape.
const SPKI_PREFIX = Buffer.from("302a300506032b6570032100", "hex");

/** Decode the two-line .sig/.pub text form into its raw bytes, size-checked. */
export function decodeKeyBlock(text: string, expected: number, which: string): Buffer {
	const lines = text.split("\n").map((line) => line.trim()).filter((line) => line.length > 0);
	const raw = Buffer.from(lines[lines.length - 1], "base64");
	if (raw.length !== expected) {
		throw new Error(`${which}: expected ${expected} bytes after base64 decoding, got ${raw.length}`);
	}
	return raw;
}

export function readPublicKey(pubText: string): KeyObject {
	return createPublicKey({
		key: Buffer.concat([SPKI_PREFIX, decodeKeyBlock(pubText, 32, "public key")]),
		format: "der",
		type: "spki",
	});
}

/** True only when the archive's exact bytes verify; false for a wrong key or a tampered or corrupted signature. */
export function verifyWebDist(
	archive: Buffer,
	sigText: string,
	pubText: string,
): boolean {
	return cryptoVerify(
		null,
		archive,
		readPublicKey(pubText),
		decodeKeyBlock(sigText, 64, "signature"),
	);
}